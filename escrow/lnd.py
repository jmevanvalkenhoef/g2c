"""LNDNode — LND REST backend for the escrow (mainnet/VPS profile).

Auth: TLS cert + admin macaroon (macaroon optional for --no-macaroons labs).
Hold invoices: created HASH-ONLY (r_hash, no preimage) where the LND build
supports it; if this build insists on a preimage we fall back once and
remember (log line makes it visible — the preimage is ours, generated by us,
so on a self-hosted node this stays within spec §2's accepted trade-off).
"""
import base64
import json
import os
from pathlib import Path
from typing import Optional

import httpx

from node import NodeError


def _b64(hexstr: str) -> str:
    return base64.b64encode(bytes.fromhex(hexstr)).decode()


class LNDNode:
    def __init__(self, rest_url: Optional[str] = None,
                 cert_path: Optional[str] = None,
                 macaroon_path: Optional[str] = None,
                 network: Optional[str] = None,
                 require_macaroon: bool = False):
        self.url = (rest_url or os.environ.get(
            "LND_REST_URL", "https://localhost:8080")).rstrip("/")
        cert = cert_path or os.environ.get("LND_TLS_CERT")
        if cert:
            # a configured cert that is missing must fail loudly: silently
            # dropping TLS verification on mainnet is not a fallback
            if not Path(cert).exists():
                raise NodeError(f"LND_TLS_CERT {cert} does not exist")
            self.client = httpx.Client(verify=cert, timeout=60)
        else:
            # lab convenience: no cert configured at all
            print("[lnd] WARNING: no LND_TLS_CERT configured, TLS NOT verified")
            self.client = httpx.Client(verify=False, timeout=60)
        self.headers = {}
        mac = macaroon_path or os.environ.get("LND_MACAROON")
        if mac and Path(mac).exists():
            self.headers["Grpc-Metadata-macaroon"] = Path(mac).read_bytes().hex()
        elif require_macaroon and mac:
            raise NodeError(f"LND_MACAROON {mac} does not exist")

    # -------------------------------------------------------------- plumbing

    def _req(self, method: str, path: str, body: Optional[dict] = None,
             timeout: Optional[float] = None) -> dict:
        try:
            r = self.client.request(method, self.url + path, json=body,
                                    headers=self.headers, timeout=timeout)
        except httpx.HTTPError as e:
            raise NodeError(f"lnd unreachable: {e}") from e
        if r.status_code >= 400:
            raise NodeError(f"lnd {path} -> {r.status_code}: {r.text[:200]}")
        return r.json() if r.content else {}

    # -------------------------------------------------------------- interface

    def get_info(self) -> dict:
        return self._req("GET", "/v1/getinfo")

    def create_hold_invoice(self, payment_hash_hex: str, amount_msat: int,
                            expiry_s: int = 3600,
                            cltv_expiry: Optional[int] = None) -> str:
        """LND v0.21+ invoices v2 API: HASH-ONLY by design — the request
        takes the hash and there is NO preimage field anywhere until settle
        time (verified against the v0.21.3 proto and live node).
        cltv_expiry = final CLTV delta the buyer's HTLC must carry: our time
        budget (in blocks) before LND auto-cancels a held HTLC."""
        body = {"value_msat": str(amount_msat),
                "expiry": str(expiry_s),
                "hash": _b64(payment_hash_hex)}
        if cltv_expiry:
            body["cltv_expiry"] = str(cltv_expiry)
        res = self._req("POST", "/v2/invoices/hodl", body)
        return res["payment_request"]

    def settle_hold_invoice(self, preimage_hex: str) -> None:
        self._req("POST", "/v2/invoices/settle", {"preimage": _b64(preimage_hex)})

    def cancel_hold_invoice(self, payment_hash_hex: str) -> None:
        self._req("POST", "/v2/invoices/cancel",
                  {"payment_hash": _b64(payment_hash_hex)})

    def _lookup_invoice(self, payment_hash_hex: str) -> dict:
        # LookupInvoiceV2 accepts payment_hash | payment_addr | set_id.
        # Query params need URL-encoding: raw base64 padding ('=') and
        # '+' are rejected by grpc-gateway ("illegal base64 data").
        from urllib.parse import quote
        return self._req("GET", "/v2/invoices/lookup?payment_hash="
                         + quote(_b64(payment_hash_hex), safe=""))

    def hold_invoice_state(self, payment_hash_hex: str) -> Optional[str]:
        try:
            res = self._lookup_invoice(payment_hash_hex)
        except NodeError:
            return None
        # OPEN | ACCEPTED | SETTLED | CANCELED
        return {"OPEN": "open", "ACCEPTED": "accepted", "SETTLED": "settled",
                "CANCELED": "cancelled"}.get(res.get("state"))

    def hold_blocks_left(self, payment_hash_hex: str) -> Optional[int]:
        """Blocks until the earliest held HTLC of this invoice expires (LND
        auto-cancels it a few blocks before that). None = no held HTLC or
        unknown; raises NodeError if the node is unreachable."""
        res = self._lookup_invoice(payment_hash_hex)
        heights = [int(h["expiry_height"]) for h in res.get("htlcs", [])
                   if h.get("state") == "ACCEPTED" and h.get("expiry_height")]
        if not heights:
            return None
        return min(heights) - int(self.get_info()["block_height"])

    def pay_invoice(self, bolt11: str, timeout_s: int,
                    fee_limit_msat: int = 1_000_000,
                    cltv_limit: Optional[int] = None) -> tuple[bool, str]:
        """LND 0.21+: POST /v2/router/send (streaming RPC -> the REST
        gateway returns the full stream as a JSON array; take the last).

        Returns (done, detail). done=False does NOT mean the payment failed:
        an HTLC can stay in flight long after timeout_s (that is only the
        pathfinding budget). Callers must decide via payment_state()."""
        body = {"payment_request": bolt11,
                "timeout_seconds": int(timeout_s),
                "fee_limit_msat": str(int(fee_limit_msat)),
                "no_inflight_updates": True}
        if cltv_limit:
            body["cltv_limit"] = int(cltv_limit)
        try:
            r = self.client.request(
                "POST", self.url + "/v2/router/send", json=body,
                headers=self.headers, timeout=timeout_s + 15)
            if r.status_code >= 400:
                return False, f"lnd pay -> {r.status_code}: {r.text[:150]}"
            res = r.json()
            if isinstance(res, list):
                res = res[-1] if res else {}
            # LND's REST stream wraps each message: {"result": {...}}
            if isinstance(res, dict) and "result" in res and isinstance(res["result"], dict):
                res = res["result"]
            status = res.get("status", "")
            if status == "SUCCEEDED":
                return True, "complete"
            if status in ("IN_FLIGHT", "INITIATED"):
                return False, "pending"
            reason = res.get("failure_reason", "") or status or "unknown"
            return False, f"pay failed: {reason}"
        except httpx.HTTPError as e:
            return False, f"lnd pay ambiguous: {e}"

    def _track(self, payment_hash_hex: str) -> Optional[dict]:
        """TrackPaymentV2 by hash: the first stream message is the current
        Payment. None = no payment with this hash was ever initiated; raises
        NodeError when LND can't be asked (unknown is NOT 'not found')."""
        path = ("/v2/router/track/"
                + base64.urlsafe_b64encode(bytes.fromhex(payment_hash_hex)).decode()
                + "?no_inflight_updates=false")
        try:
            with self.client.stream("GET", self.url + path, headers=self.headers,
                                    timeout=20) as r:
                line = next((ln for ln in r.iter_lines() if ln.strip()), "")
        except httpx.HTTPError as e:
            raise NodeError(f"lnd track unreachable: {e}") from e
        try:
            msg = json.loads(line) if line else {}
        except json.JSONDecodeError as e:
            raise NodeError(f"lnd track: bad response {line[:150]!r}") from e
        err = msg.get("error") or (msg if r.status_code >= 400 else None)
        if err:
            text = str(err.get("message", err)).lower()
            if "not initiated" in text or "isn't initiated" in text or "not found" in text:
                return None
            raise NodeError(f"lnd track error: {text[:150]}")
        return msg.get("result") or msg

    def payment_state(self, payment_hash_hex: str) -> Optional[str]:
        pay = self._track(payment_hash_hex)
        if pay is None:
            return None
        return {"SUCCEEDED": "complete", "FAILED": "failed",
                "IN_FLIGHT": "pending", "INITIATED": "pending"}.get(
                    pay.get("status"), "pending")

    def payment_fee_msat(self, payment_hash_hex: str) -> Optional[int]:
        """routing fee of a SUCCEEDED payment (None: not succeeded/unknown)"""
        pay = self._track(payment_hash_hex)
        if not pay or pay.get("status") != "SUCCEEDED" or "fee_msat" not in pay:
            return None
        return int(pay["fee_msat"])

    def decode_invoice(self, bolt11: str) -> dict:
        d = self._req("GET", f"/v1/payreq/{bolt11}")
        amt = d.get("num_msat")
        return {"payment_hash": d.get("payment_hash"),
                "amount_msat": int(amt) if amt not in (None, "") else None}

    # -------------------------------------------------------------- lab profile

    def create_invoice(self, amount_msat: int, label: str, desc: str) -> tuple[str, str]:
        res = self._req("POST", "/v1/invoices",
                        {"value_msat": str(amount_msat), "memo": label})
        return res["payment_request"], res["r_hash"]

    def find_invoice_by_label(self, label: str) -> Optional[dict]:
        res = self._req("GET", "/v1/invoices?num_max_invoices=500")
        invs = [i for i in res.get("invoices", []) if i.get("memo") == label]
        if not invs:
            return None
        inv = invs[-1]
        st = inv.get("state")
        return {"bolt11": inv.get("payment_request"),
                "payment_hash": inv.get("r_hash", ""),
                "state": {"SETTLED": "settled", "CANCELED": "cancelled"}.get(st, "open")}

    # -------------------------------------------------------------- admin (lab setup)

    def genseed(self) -> list[str]:
        return self._req("GET", "/v1/genseed")["cipher_seed_mnemonic"]

    def init_wallet(self, password: str, mnemonic: Optional[list[str]] = None) -> None:
        body = {"wallet_password": base64.b64encode(password.encode()).decode()}
        if mnemonic:
            body["cipher_seed_mnemonic"] = mnemonic
        self._req("POST", "/v1/initwallet", body)

    def unlock_wallet(self, password: str) -> bool:
        try:
            self._req("POST", "/v1/unlockwallet",
                      {"wallet_password": base64.b64encode(password.encode()).decode()})
            return True
        except NodeError:
            return False

    def new_address(self) -> str:
        # GET with query param (POST returns 501 on 0.21.x)
        return self._req("GET", "/v1/newaddress?type=0")["address"]

    def connect_peer(self, node_id: str, host: str) -> None:
        try:
            self._req("POST", "/v1/peers",
                      {"addr": {"pubkey": node_id, "host": host}})
        except NodeError as e:
            if "already connected" not in str(e).lower():
                raise

    def open_channel(self, node_id: str, amount_sat: int,
                     push_sat: int = 0, private: bool = True) -> str:
        res = self._req("POST", "/v1/channels",
                        {"node_pubkey_string": node_id,
                         "local_funding_amount": str(amount_sat),
                         "push_sat": str(push_sat),
                         "private": private, "min_confs": 1},
                        timeout=60)
        return res.get("funding_txid_str") or res.get("funding_txid", "")
